        failed_nodes = sum(1 for node in nodes if node.get("state") == "failed")
        
        if intent["type"] == "troubleshooting" and failed_nodes > 0:
            return f"Among the {total_nodes} selected nodes, {failed_nodes} have failed and {completed_nodes} completed successfully. I can help you identify common failure patterns and suggest solutions. Would you like me to analyze the errors systematically?"
            
        elif intent["type"] == "data_analysis":
            return f"You've selected {total_nodes} analysis nodes with {completed_nodes} completed successfully. I can help you understand how these steps work together, compare their results, or suggest ways to integrate their outputs for comprehensive analysis."
            
        else:
            return f"You've selected {total_nodes} analysis nodes ({completed_nodes} successful, {failed_nodes} failed). I can help you understand the relationships between these steps, compare results, or troubleshoot issues. What would you like to focus on?"

