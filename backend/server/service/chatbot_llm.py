    def generate_response(self, 
                         content: str, 
                         context_type: str,
                         context_data: Optional[Dict] = None,
                         analysis_id: Optional[int] = None,
                         user_id: Optional[int] = None) -> Tuple[str, List[Dict]]:
        """
        Generate intelligent response for the bioinformatics chatbot
        
        Args:
            content: User's message/question
            context_type: Type of context ('analysis', 'pipeline', 'node', 'multinodes')
            context_data: Additional context information
            analysis_id: Current analysis ID
            user_id: User ID
            
        Returns:
            Tuple of (response_text, recommended_functionalities)
        """
        
        try:
            # Analyze user input and determine intent
            intent = self._analyze_user_intent(content)
            
            # Try to generate response using real LLM first
            response_text = self._generate_llm_response(
                content, intent, context_type, context_data, analysis_id, user_id
            )
            
            # Get functionality recommendations
            recommended_functionalities = self._get_functionality_recommendations(
                content, intent, context_type
            )
            
            return response_text, recommended_functionalities
            
        except Exception as e:
            logger.error(f"Error generating chatbot response: {e}")
            return self._get_fallback_response(context_type), []

    def _analyze_user_intent(self, content: str) -> Dict[str, Any]:
        """Analyze user's message to understand their intent"""
        content_lower = content.lower()
        
        intent = {
            "type": "general",
            "confidence": 0.5,
            "keywords": [],
            "bioinformatics_topic": None,
            "analysis_type": None,
            "data_type": None
        }
        
        # Define intent patterns
        intent_patterns = {
            "data_analysis": ["analyze", "analysis", "statistical", "statistics", "correlation", "comparison"],
            "visualization": ["plot", "chart", "graph", "visualize", "figure", "show", "display"],
            "data_import": ["import", "upload", "load", "data", "dataset", "file"],
            "pipeline": ["pipeline", "workflow", "process", "steps", "analysis flow"],
            "troubleshooting": ["error", "bug", "problem", "issue", "fix", "debug", "help"],
        }
        
        # Bioinformatics-specific patterns
        bioinformatics_patterns = {
            "genomics": ["gene", "genome", "dna", "rna", "sequencing", "variant", "mutation"],
            "transcriptomics": ["expression", "rna-seq", "transcript", "differential expression"],
            "proteomics": ["protein", "proteome", "mass spec", "peptide"],
            "single_cell": ["single cell", "scRNA-seq", "cell type", "clustering"],
            "pathway": ["pathway", "enrichment", "go", "kegg", "reactome"],
            "quality_control": ["quality", "qc", "filter", "normalization"]
        }
        
        # Check for intent patterns
        for intent_type, keywords in intent_patterns.items():
            for keyword in keywords:
                if keyword in content_lower:
                    intent["type"] = intent_type
                    intent["keywords"].append(keyword)
                    intent["confidence"] = min(1.0, intent["confidence"] + 0.2)
        
        # Check for bioinformatics topics
        for topic, keywords in bioinformatics_patterns.items():
            for keyword in keywords:
                if keyword in content_lower:
                    intent["bioinformatics_topic"] = topic
                    intent["confidence"] = min(1.0, intent["confidence"] + 0.3)
        
        return intent

    def _generate_llm_response(self,
                              content: str,
                              intent: Dict[str, Any],
                              context_type: str,
                              context_info: Dict[str, Any],
                              analysis_id: Optional[int] = None,
                              user_id: Optional[int] = None) -> str:
        try:
            # Build system prompt for bioinformatics assistant
            system_prompt = self._build_system_prompt(context_type, context_info)

            # Create user message with context
            user_message = self._build_user_message(content, intent)

            # Call LLM API through existing interface
            response = self._call_chatbot_llm_api(
                system_prompt, user_message, analysis_id, user_id
            )

            logger.info(f"LLM API response: {response}")
            
            if response and response.get('status') == 'finished':
                return response.get('response', self._get_fallback_response(context_type))
            else:
                logger.warning("LLM API call failed, using fallback response")
                return LLM_UNAVAILABLE_NOTICE + self._generate_contextual_response(content, intent, context_type, context_info)
                
        except Exception as e:
            logger.error(f"Error calling LLM API: {e}")
            # Fallback: template-based response, explicitly labelled as not model-generated
            return LLM_UNAVAILABLE_NOTICE + self._generate_contextual_response(content, intent, context_type, context_info)

    def _build_system_prompt(self, context_type: str, context_info: Dict[str, Any]) -> str:
        """Build system prompt for the LLM based on context"""
        
        base_prompt = """You are a specialized bioinformatics AI assistant for the OmiCairn platform. You help users with:
        
        - Genomics analysis (variant calling, genome annotation, comparative genomics)
        - Transcriptomics (RNA-seq, differential expression, transcript assembly)
        - Single-cell analysis (quality control, clustering, cell type identification)  
        - Proteomics (mass spectrometry, protein identification)
        - Pathway analysis (gene set enrichment, functional annotation)
        - Data visualization and interpretation
        - Pipeline troubleshooting and optimization
        - and more
        
        Provide concise, helpful responses (2-3 sentences max). Be specific about bioinformatics methods and tools when relevant.
        
        IMPORTANT: Do not recommend external tools or platforms. Focus on helping with analysis concepts, interpretation, and troubleshooting."""
        
        # Add context-specific information
        if context_type == "analysis":
            analysis_info = context_info.get("analysis_info", {})
            data_count = analysis_info.get("data_count", 0)
            has_results = analysis_info.get("has_results", False)
            data_types = analysis_info.get("data_types", [])
            
            context_prompt = f"""
            
            CURRENT ANALYSIS CONTEXT:
            - Data uploaded: {data_count} dataset(s)
            - Data types: {', '.join(set(data_types)) if data_types else 'None'}
            - Has computational results: {'Yes' if has_results else 'No'}
            """
            
        elif context_type == "pipeline":
            nodes = context_info.get("nodes", [])
            computations = context_info.get("computations", {})
            
            completed_nodes = sum(1 for node in nodes if node.get("state") == "finished")
            failed_nodes = sum(1 for node in nodes if node.get("state") == "failed")
            running_nodes = sum(1 for node in nodes if node.get("state") == "running")
            
            node_types = [node.get("type", "unknown") for node in nodes]
            unique_types = list(set(node_types))
            
            context_prompt = f"""
            
            CURRENT PIPELINE CONTEXT:
            - Total analysis steps: {len(nodes)}
            - Completed successfully: {completed_nodes}
            - Currently running: {running_nodes}
            - Failed: {failed_nodes}
            - Node types: {', '.join(unique_types[:3])}
            - Pipeline steps: {', '.join([node.get('name', 'Unknown') for node in nodes[:5]])}
            """
            
            if computations:
                comp_states = [comp.get("computation_state", "unknown") for comp in computations.values()]
                finished_comps = sum(1 for state in comp_states if state == "finished")
                failed_comps = sum(1 for state in comp_states if state == "failed")
                if finished_comps > 0 or failed_comps > 0:
                    context_prompt += f"""
            - Computations: {finished_comps} finished, {failed_comps} failed"""
            
        elif context_type == "node":
            node = context_info.get("node", {})
            computation = context_info.get("computation", {})
            
            node_name = node.get("name", "Unknown")
            node_type = node.get("type", "Unknown")
            node_state = node.get("state", "Unknown")
            
            context_prompt = f"""
            
            CURRENT NODE CONTEXT:
            - Node name: {node_name}
            - Node type: {node_type}
            - Status: {node_state}
            """
            
            # Add computation details if available
            if computation:
                comp_state = computation.get("computation_state", "Unknown")
                duration = computation.get("duration")
                error_msg = computation.get("error_message")
                
                context_prompt += f"""
            - Computation state: {comp_state}"""
                
                if duration:
                    context_prompt += f"""
            - Duration: {duration}s"""
                    
                if error_msg and node_state == "failed":
                    context_prompt += f"""
            - Error occurred: Yes (details available)"""
                
                if computation.get("result_data_id"):
                    context_prompt += f"""
            - Has results: Yes"""
                    
        elif context_type == "multinodes":
            nodes = context_info.get("nodes", [])
            computations = context_info.get("computations", {})
            
            completed = sum(1 for node in nodes if node.get("state") == "finished")
            failed = sum(1 for node in nodes if node.get("state") == "failed")
            running = sum(1 for node in nodes if node.get("state") == "running")
            
            node_types = list(set(node.get("type", "unknown") for node in nodes))
            node_names = [node.get("name", "Unknown") for node in nodes[:5]]
            
            context_prompt = f"""
            
            CURRENT MULTI-NODE CONTEXT:
            - Selected nodes: {len(nodes)}
            - Completed: {completed}
            - Running: {running}
            - Failed: {failed}
            - Node types: {', '.join(node_types[:3])}
            - Node names: {', '.join(node_names)}
            """
            
            if computations:
                comp_states = [comp.get("computation_state", "unknown") for comp in computations.values()]
                finished_comps = sum(1 for state in comp_states if state == "finished")
                failed_comps = sum(1 for state in comp_states if state == "failed")
                
                context_prompt += f"""
            - Computations: {finished_comps} finished, {failed_comps} failed"""
                
        else:
            context_prompt = ""
            
        return base_prompt + context_prompt

    def _build_user_message(self, content: str, intent: Dict[str, Any]) -> str:
        """Build user message with intent and context information"""
        
        message = f"User question: {content}"
        
        # Add intent information
        if intent.get("bioinformatics_topic"):
            message += f"\nBioinformatics topic: {intent['bioinformatics_topic']}"
            
        if intent.get("type") != "general":
            message += f"\nUser intent: {intent['type']}"
            
        return message

    def _call_chatbot_llm_api(self, 
                             system_prompt: str, 
                             user_message: str,
                             analysis_id: Optional[int] = None,
                             user_id: Optional[int] = None) -> Optional[Dict[str, Any]]:
        """
        Call the chatbot LLM API (similar to how Auto Genie calls GPT-4o)
        """
        try:
            url = f"http://{GPT_WORKFLOW_SERVER_HOST}:{GPT_WORKFLOW_SERVER_PORT}/chatbot/generate_response"
            
            payload = {
                "system_prompt": system_prompt,
                "user_message": user_message,
                "analysis_id": analysis_id,
                "user_id": user_id,
                "model": "gpt-4o-mini",
                "max_tokens": 500,  # Limit response length
                "temperature": 0.7  # Balanced creativity vs consistency
            }
            
            response = requests.post(
                url=url,
                json=payload,
                proxies=PROXIES,
                timeout=30  # 30 second timeout
            )
            
            if response.status_code == 200:
                response_data = response.json()
                data = response_data.get('data', {})
                return {
                    'status': 'finished',
                    'response': data.get('response', ''),
                    'usage': data.get('usage', {})
                }
            else:
                logger.error(f"LLM API returned status {response.status_code}: {response.text}")
                return None
                
        except requests.exceptions.Timeout:
            logger.error("LLM API call timed out")
            return None
        except Exception as e:
            logger.error(f"Error calling LLM API: {e}")
            return None

    def _generate_contextual_response(self, 
                                    content: str, 
                                    intent: Dict[str, Any],
                                    context_type: str,
                                    context_info: Dict[str, Any]) -> str:
        """Generate contextual response based on user input and context"""
        
